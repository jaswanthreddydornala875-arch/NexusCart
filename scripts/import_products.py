#!/usr/bin/env python3
"""Bulk-import products from a CSV, TSV, JSON, JSONL or Excel (.xlsx) file.

    python3 scripts/import_products.py database/products.csv --dry-run     # check only, change nothing
    python3 scripts/import_products.py database/products.csv               # import / update the database
    python3 scripts/import_products.py new_stock.xlsx --copy-images ~/Pictures/new_stock
    python3 scripts/import_products.py database/products.csv --no-db --emit-sql database/seed.sql

What it does
  * reads the file and maps column names ("Title" -> name, "Qty" -> stock, ...)
  * checks every row (required fields, price / stock numbers, duplicate SKUs ...) and reports
    problems by row number; bad rows are skipped and written to import_errors.csv
  * finds each product's picture in frontend/assets/images/<category>/ (or copies it there)
  * inserts new products and updates existing ones, matched by SKU (safe to run again)
  * can also write the products as SQL into database/seed.sql for Docker / fresh databases

Columns:  sku, name*, category*, brand, price*, stock, description, image, is_active   (* = required)
See docs/bulk_import.md for details.
"""
import argparse
import csv
import json
import os
import re
import shutil
import sys
import warnings
from collections import Counter
from decimal import Decimal, InvalidOperation
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DEFAULT_IMAGES = REPO / "frontend" / "assets" / "images"
IMAGE_EXTS = (".png", ".jpg", ".jpeg", ".gif", ".webp")
REQUIRED = ("name", "category", "price")

ALIASES = {
    "sku": {"sku", "product_code", "item_code", "code", "product_sku"},
    "name": {"name", "title", "product", "product_name", "item", "item_name"},
    "category": {"category", "department", "product_type", "type", "category_name"},
    "brand": {"brand", "manufacturer", "vendor", "make"},
    "price": {"price", "unit_price", "selling_price", "sale_price", "cost", "amount", "price_usd", "mrp"},
    "stock": {"stock", "quantity", "qty", "inventory", "units", "stock_quantity", "in_stock"},
    "description": {"description", "desc", "details", "about", "product_description"},
    "image": {"image", "image_path", "image_file", "picture", "photo", "filename", "img"},
    "is_active": {"is_active", "active", "enabled", "status", "available"},
}
TRUE_WORDS = {"1", "true", "yes", "y", "active", "enabled", "on", "available", "t"}
FALSE_WORDS = {"0", "false", "no", "n", "inactive", "disabled", "off", "unavailable", "f", "draft"}
BEGIN = "-- BEGIN PRODUCTS (generated by scripts/import_products.py - edit database/products.csv, then re-run with --emit-sql)"
END = "-- END PRODUCTS"


class ImportFailure(Exception):
    """A problem with the whole file (not just one row)."""


# ------------------------------------------------------------------ small parsers
def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", str(text).lower()).strip("-")


def parse_price(text):
    s = str(text).strip()
    if not s:
        raise ValueError("price is empty")
    cleaned = re.sub(r"[^\d.\-]", "", s.replace(",", ""))
    try:
        value = Decimal(cleaned)
    except InvalidOperation:
        raise ValueError(f"'{s}' is not a valid price")
    if value < 0:
        raise ValueError("price cannot be negative")
    if value > Decimal("10000000"):
        raise ValueError("price is unrealistically large")
    return value.quantize(Decimal("0.01"))


def parse_stock(text):
    s = str(text).strip()
    if not s:
        return 0
    try:
        value = Decimal(s.replace(",", ""))
    except InvalidOperation:
        raise ValueError(f"'{s}' is not a whole number")
    if value != value.to_integral_value():
        raise ValueError(f"stock must be a whole number, not '{s}'")
    if value < 0:
        raise ValueError("stock cannot be negative")
    return int(value)


def parse_bool(text):
    s = str(text).strip().lower()
    if not s:
        return True
    if s in TRUE_WORDS:
        return True
    if s in FALSE_WORDS:
        return False
    raise ValueError(f"'{text}' is not yes/no (use true/false, yes/no or 1/0)")


def norm_header(h):
    """'Price (INR)' -> 'price', 'Product Name' -> 'product_name', '\ufeffSKU' -> 'sku'."""
    h = re.sub(r"\(.*?\)|\[.*?\]", "", str(h).replace("\ufeff", ""))       # drop units: "(INR)", "[USD]"
    return re.sub(r"[\s\-/]+", "_", h.strip().lower()).strip("_")


def map_headers(headers):
    """raw header -> canonical column name (unknown headers are left out)."""
    out = {}
    for raw in headers:
        n = norm_header(raw)
        for canon, names in ALIASES.items():
            if n in names and canon not in out.values():
                out[raw] = canon
                break
    return out


# ------------------------------------------------------------------ reading files
def read_table(path, sheet=None):
    """Returns ([(row_number, {header: value})], [headers]) for csv/tsv/json/jsonl/xlsx."""
    path = Path(path)
    if not path.is_file():
        raise ImportFailure(f"File not found: {path}")
    ext = path.suffix.lower()
    if ext in (".csv", ".tsv", ".txt"):
        with open(path, newline="", encoding="utf-8-sig") as f:
            sample = f.read(4096)
            f.seek(0)
            delim = "\t" if ext == ".tsv" else ","
            if ext != ".tsv":
                try:
                    delim = csv.Sniffer().sniff(sample, delimiters=",;\t|").delimiter
                except csv.Error:
                    pass
            reader = csv.DictReader(f, delimiter=delim)
            rows = [(i, dict(r)) for i, r in enumerate(reader, start=2)]
            return rows, list(reader.fieldnames or [])
    if ext in (".json", ".jsonl", ".ndjson"):
        text = path.read_text(encoding="utf-8-sig")
        try:
            if ext == ".json":
                data = json.loads(text)
                if isinstance(data, dict):
                    data = next((v for v in data.values() if isinstance(v, list)), None) or [data]
            else:
                data = [json.loads(line) for line in text.splitlines() if line.strip()]
        except json.JSONDecodeError as e:
            raise ImportFailure(f"{path.name} is not valid JSON: {e}")
        if not all(isinstance(d, dict) for d in data):
            raise ImportFailure("JSON must be a list of objects, e.g. [{\"name\": ..., \"price\": ...}]")
        headers = list(dict.fromkeys(k for d in data for k in d))
        return [(i, {k: ("" if v is None else v) for k, v in d.items()}) for i, d in enumerate(data, start=1)], headers
    if ext in (".xlsx", ".xlsm"):
        try:
            from openpyxl import load_workbook
        except ImportError:
            raise ImportFailure("Reading Excel files needs openpyxl:  pip install openpyxl")
        wb = load_workbook(path, read_only=True, data_only=True)
        ws = wb[sheet] if sheet else wb.worksheets[0]
        it = ws.iter_rows(values_only=True)
        headers = [str(h).strip() if h is not None else "" for h in next(it, [])]
        rows = []
        for i, values in enumerate(it, start=2):
            if all(v in (None, "") for v in values):
                continue
            rows.append((i, {h: ("" if v is None else v) for h, v in zip(headers, values) if h}))
        return rows, [h for h in headers if h]
    raise ImportFailure(f"Unsupported file type '{ext}'. Use .csv, .tsv, .json, .jsonl or .xlsx")


# ------------------------------------------------------------------ validation
def _text(v):
    return re.sub(r"[ \t]+", " ", str(v).strip()) if v is not None else ""


def make_sku(category, name):
    prefix = re.sub(r"[^A-Z0-9]", "", category.upper())[:3] or "GEN"
    return f"{prefix}-{slug(name).upper()}"[:40]


def clean_rows(rows, headers):
    """Returns (records, issues). Rows with an error are left out of records; issues is a list of
    {"row", "level", "field", "message"} for errors and warnings."""
    hmap = map_headers(headers)
    canon = set(hmap.values())
    missing = [c for c in REQUIRED if c not in canon]
    if missing:
        raise ImportFailure(
            f"Required column(s) missing: {', '.join(missing)}.\n"
            f"  Found columns: {', '.join(map(str, headers)) or '(none)'}\n"
            f"  Needed: name, category, price (optional: sku, brand, stock, description, image, is_active)")
    issues = [{"row": 0, "level": "warning", "field": "", "message": f"ignored unknown column '{h}'"}
              for h in headers if h not in hmap and str(h).strip()]
    records, seen_sku = [], {}
    for rownum, raw in rows:
        r = {canon_name: _text(raw.get(h, "")) for h, canon_name in hmap.items()}
        errs = []

        def err(field, msg):
            errs.append({"row": rownum, "level": "error", "field": field, "message": msg})

        name, category = r.get("name", ""), r.get("category", "")
        if not name:
            err("name", "name is required")
        elif len(name) > 150:
            err("name", "name is longer than 150 characters")
        if not category:
            err("category", "category is required")
        elif len(category) > 60:
            err("category", "category is longer than 60 characters")
        elif category.islower() or category.isupper():
            category = category.title()
        price = stock = None
        try:
            price = parse_price(r.get("price", ""))
        except ValueError as e:
            err("price", str(e))
        try:
            stock = parse_stock(r.get("stock", ""))
        except ValueError as e:
            err("stock", str(e))
        try:
            active = parse_bool(r.get("is_active", ""))
        except ValueError as e:
            err("is_active", str(e))
            active = True
        brand = r.get("brand", "")
        if len(brand) > 80:
            err("brand", "brand is longer than 80 characters")
        sku = r.get("sku", "").upper().replace(" ", "-")
        generated = not sku
        if sku and not re.fullmatch(r"[A-Z0-9._\-]{1,40}", sku):
            err("sku", "sku may only contain letters, numbers, . _ - (max 40 characters)")
        if generated and name and category:
            sku = make_sku(category, name)
        if sku and not errs:
            if sku in seen_sku:
                err("sku", f"duplicate SKU {sku} (first used on row {seen_sku[sku]})")
            else:
                seen_sku[sku] = rownum
        if errs:
            issues.extend(errs)
            continue
        if stock == 0 and active:
            issues.append({"row": rownum, "level": "warning", "field": "stock", "message": "stock is 0 (shown as unavailable)"})
        if generated:
            issues.append({"row": rownum, "level": "warning", "field": "sku", "message": f"no SKU given, using {sku}"})
        records.append({"row": rownum, "sku": sku, "sku_given": not generated, "name": name, "category": category,
                        "brand": brand, "price": price, "stock": stock, "description": r.get("description", ""),
                        "image": r.get("image", ""), "image_path": None, "is_active": active})
    return records, issues


# ------------------------------------------------------------------ images
def _find(root, stems):
    for stem in stems:
        if not stem:
            continue
        p = root / stem
        if p.suffix.lower() in IMAGE_EXTS and p.is_file():
            return p
        for ext in IMAGE_EXTS:
            q = root / f"{stem}{ext}"
            if q.is_file():
                return q
    return None


def resolve_images(records, images_dir, copy_from=None, organize=False, dry_run=False):
    """Sets rec["image_path"] (relative to images_dir, e.g. 'electronics/wireless-mouse.png').
    copy_from: a folder of pictures to copy into the category folders.
    organize: move pictures lying loose in images_dir into their category folder."""
    images_dir = Path(images_dir)
    copy_from = Path(copy_from) if copy_from else None
    stats = Counter()
    for rec in records:
        given = rec["image"].strip()
        if given.lower().startswith(("http://", "https://")):
            rec["image_path"] = given
            stats["remote"] += 1
            continue
        cat = slug(rec["category"])
        stems = ([given] if given else []) + [rec["sku"].lower(), slug(rec["name"])]
        found = _find(images_dir / cat, stems) or _find(images_dir, stems)
        if found is None and given:
            rel = images_dir / given
            found = rel if rel.is_file() else None
        if found is None and copy_from is not None:
            src = _find(copy_from / cat, stems) or _find(copy_from, stems)
            if src is not None:
                final = (rec["sku"].lower() if rec["sku_given"] else slug(rec["name"])) + src.suffix.lower()
                dest = images_dir / cat / final
                if not dest.exists() and not dry_run:
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(src, dest)
                rec["image_path"] = f"{cat}/{final}"
                stats["copied"] += 1
                continue
        if found is None:
            stats["missing"] += 1
            rec["_image_missing"] = True
            continue
        if organize and found.parent == images_dir:
            dest = images_dir / cat / found.name
            if not dry_run:
                dest.parent.mkdir(parents=True, exist_ok=True)
                if not dest.exists():
                    shutil.move(str(found), str(dest))
            rec["image_path"] = f"{cat}/{found.name}"
            stats["moved"] += 1
            continue
        rec["image_path"] = found.relative_to(images_dir).as_posix() if images_dir in found.parents else found.name
        stats["found"] += 1
    return stats


# ------------------------------------------------------------------ database
def _fields(r):
    return {"sku": r["sku"], "name": r["name"], "category": r["category"], "brand": r["brand"] or None,
            "price": r["price"], "stock": r["stock"], "description": r["description"],
            "image_path": r["image_path"], "is_active": r["is_active"]}


def write_db(app, records, mode="upsert", dry_run=False, create_table=False, batch=500):
    """mode: upsert (insert new + update existing) | insert (skip existing) | update (skip new)."""
    from sqlalchemy import inspect

    from app.extensions import db
    from app.models.product import Product

    stats = Counter()
    with app.app_context():
        engine = db.engine
        exists = inspect(engine).has_table(Product.__tablename__)
        if not exists:
            if not (engine.dialect.name == "sqlite" or create_table):
                raise ImportFailure("The products table does not exist yet. Run database/schema.sql first "
                                    "(or add --create-table for a throw-away database).")
            if dry_run:
                stats["inserted"] = len(records) if mode != "update" else 0
                stats["skipped_missing"] = len(records) if mode == "update" else 0
                return stats
            Product.__table__.create(engine)
        try:
            for i in range(0, len(records), batch):
                chunk = records[i:i + batch]
                existing = {p.sku: p for p in Product.query.filter(Product.sku.in_([r["sku"] for r in chunk])).all()}
                for r in chunk:
                    p = existing.get(r["sku"])
                    if p is None:
                        if mode == "update":
                            stats["skipped_missing"] += 1
                            continue
                        db.session.add(Product(**_fields(r)))
                        stats["inserted"] += 1
                    else:
                        if mode == "insert":
                            stats["skipped_existing"] += 1
                            continue
                        for k, v in _fields(r).items():
                            setattr(p, k, v)
                        stats["updated"] += 1
                db.session.flush()
            if dry_run:
                db.session.rollback()
            else:
                db.session.commit()
        except Exception:
            db.session.rollback()
            raise
    return stats


def write_django_db(records, mode="upsert", dry_run=False, batch=500):
    """Import into the Django catalog used by the persistent storefront."""
    from django.db import connection, transaction

    from store.models import Product

    if Product._meta.db_table not in connection.introspection.table_names():
        raise ImportFailure(
            "The Django catalog table does not exist yet. Run "
            "`python3 backend/manage.py migrate` first."
        )

    stats = Counter()
    with transaction.atomic():
        for i in range(0, len(records), batch):
            chunk = records[i:i + batch]
            existing = {
                product.sku: product
                for product in Product.all_objects.filter(sku__in=[row["sku"] for row in chunk])
            }
            for row in chunk:
                product = existing.get(row["sku"])
                if product is None:
                    if mode == "update":
                        stats["skipped_missing"] += 1
                        continue
                    stats["inserted"] += 1
                    if dry_run:
                        continue
                    values = _fields(row)
                    values["brand"] = row["brand"] or ""
                    values["image_path"] = row["image_path"] or ""
                    Product.objects.create(**values)
                elif mode == "insert":
                    stats["skipped_existing"] += 1
                else:
                    stats["updated"] += 1
                    if dry_run:
                        continue
                    values = _fields(row)
                    values["brand"] = row["brand"] or ""
                    values["image_path"] = row["image_path"] or ""
                    for field, value in values.items():
                        setattr(product, field, value)
                    product.is_deleted = False
                    product.deleted_at = None
                    product.save()
        if dry_run:
            transaction.set_rollback(True)
    return stats


# ------------------------------------------------------------------ SQL seed
def _lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, Decimal)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def sql_block(records, chunk=100):
    cols = ["sku", "name", "category", "brand", "price", "stock", "description", "image_path", "is_active"]
    update = ", ".join(f"{c} = EXCLUDED.{c}" for c in cols[1:]) + ", updated_at = now()"
    parts = [BEGIN]
    for i in range(0, len(records), chunk):
        rows = ",\n".join("    (" + ", ".join(_lit(_fields(r)[c]) for c in cols) + ")" for r in records[i:i + chunk])
        parts.append(f"INSERT INTO products ({', '.join(cols)}) VALUES\n{rows}\nON CONFLICT (sku) DO UPDATE SET {update};")
    parts.append(END)
    return "\n".join(parts) + "\n"


def update_marked_block(path, block):
    """Replace the generated block inside `path` (keeps any hand-written SQL around it)."""
    path = Path(path)
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        new = head + block + ("\n" + tail if tail else "")
    else:
        new = text.rstrip("\n") + ("\n\n" if text.strip() else "") + block
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new, encoding="utf-8", newline="\n")


# ------------------------------------------------------------------ command line
def write_errors(path, issues, rows_by_number, headers):
    """Rejected rows as an ordinary table (row, problem + your original columns), so you can fix
    them in Excel and import that file again."""
    problems = {}
    for i in issues:
        if i["level"] == "error":
            problems.setdefault(i["row"], []).append(f"{i['field']}: {i['message']}" if i["field"] else i["message"])
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["row", "problem"] + list(headers))
        for row in sorted(problems):
            raw = rows_by_number.get(row, {})
            w.writerow([row, " | ".join(problems[row])] + [raw.get(h, "") for h in headers])


def mask(url):
    return re.sub(r"(://[^:/@]+:)[^@]+@", r"\1****@", url)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Bulk-import products from CSV / TSV / JSON / JSONL / XLSX.")
    ap.add_argument("file", help="products file (.csv .tsv .json .jsonl .xlsx)")
    ap.add_argument("--dry-run", action="store_true", help="check everything but change nothing")
    ap.add_argument("--strict", action="store_true", help="stop if ANY row has an error (default: skip bad rows)")
    ap.add_argument("--mode", choices=["upsert", "insert", "update"], default="upsert",
                    help="upsert (default): add new + update existing; insert: only new; update: only existing")
    ap.add_argument("--sheet", help="Excel sheet name (default: first sheet)")
    ap.add_argument("--images-dir", default=str(DEFAULT_IMAGES), help="product pictures folder")
    ap.add_argument("--copy-images", metavar="DIR", help="copy matching pictures from DIR into the category folders")
    ap.add_argument("--organize-images", action="store_true", help="move loose pictures into their category folder")
    ap.add_argument("--emit-sql", metavar="FILE", help="also write the products as SQL (e.g. database/seed.sql)")
    ap.add_argument("--no-db", action="store_true", help="do not touch the database (validate / emit SQL / images only)")
    ap.add_argument("--database-url", help="override DATABASE_URL (default: from .env, else local SQLite)")
    ap.add_argument("--django", action="store_true",
                    help="import into the Django storefront catalog instead of the Flask products table")
    ap.add_argument("--create-table", action="store_true", help="create the products table if it is missing")
    ap.add_argument("--errors-out", default="import_errors.csv", help="where to write rejected rows")
    args = ap.parse_args(argv)

    warnings.filterwarnings("ignore", message=".*does \\*not\\* support Decimal.*")
    try:
        rows, headers = read_table(args.file, args.sheet)
        records, issues = clean_rows(rows, headers)
    except ImportFailure as e:
        print(f"\nERROR: {e}")
        return 1

    errors = [i for i in issues if i["level"] == "error"]
    warns = [i for i in issues if i["level"] == "warning"]
    print(f"\nReading {args.file}")
    print(f"  {len(rows)} rows read  ->  {len(records)} valid, {len({e['row'] for e in errors})} with errors, {len(warns)} warnings")
    for i in errors[:25]:
        print(f"  ERROR   row {i['row']:>4}  {i['field']:<12} {i['message']}")
    if len(errors) > 25:
        print(f"  ... and {len(errors) - 25} more (see {args.errors_out})")
    for i in [w for w in warns if w["field"] != "stock"][:10]:
        print(f"  warning row {i['row']:>4}  {i['field']:<12} {i['message']}")
    if errors:
        write_errors(args.errors_out, issues, dict(rows), headers)
        print(f"  rejected rows written to {args.errors_out}")
    if errors and args.strict:
        print("\nStopped: --strict is on and some rows have errors. Nothing was imported.")
        return 2
    if not records:
        print("\nNothing to import.")
        return 2 if errors else 0

    img = resolve_images(records, args.images_dir, args.copy_images, args.organize_images, args.dry_run)
    print(f"Images: {img['found'] + img['copied'] + img['moved']} matched "
          f"({img['found']} in place, {img['copied']} copied, {img['moved']} moved), "
          f"{img['missing']} without a picture yet, {img['remote']} remote links")
    missing = [r["sku"] for r in records if r.get("_image_missing")]
    if missing:
        print(f"  no picture for: {', '.join(missing[:8])}{' ...' if len(missing) > 8 else ''}")
        print(f"  put <sku>.png or <name-slug>.png in {Path(args.images_dir)}/<category>/ (or use --copy-images)")

    if args.emit_sql:
        if args.dry_run:
            print(f"SQL: would update {args.emit_sql}")
        else:
            update_marked_block(args.emit_sql, sql_block(records))
            print(f"SQL: wrote {len(records)} products to {args.emit_sql}")

    if args.no_db:
        print("\nDone (database untouched: --no-db).")
        return 0

    try:
        if args.django:
            if args.database_url:
                os.environ["DATABASE_URL"] = args.database_url
            os.environ.setdefault("DJANGO_SETTINGS_MODULE", "nexus_core.settings")
            sys.path.insert(0, str(REPO / "backend"))
            import django
            django.setup()
            stats = write_django_db(records, args.mode, args.dry_run)
            from django.conf import settings
            database = settings.DATABASES["default"]
            url = (database["NAME"] if database["ENGINE"] == "django.db.backends.sqlite3"
                   else database["ENGINE"])
        else:
            sys.path.insert(0, str(REPO / "backend"))
            from app import create_app
            from app.config import Config

            class ImportConfig(Config):
                pass

            if args.database_url:
                ImportConfig.SQLALCHEMY_DATABASE_URI = args.database_url
            app = create_app(ImportConfig)
            stats = write_db(app, records, args.mode, args.dry_run, args.create_table)
            url = mask(str(app.config["SQLALCHEMY_DATABASE_URI"]))
    except ImportFailure as e:
        print(f"\nERROR: {e}")
        return 1
    except Exception as e:                                   # database problems: show a readable message
        print(f"\nDATABASE ERROR: {type(e).__name__}: {str(e).splitlines()[0]}")
        print("Nothing was changed.")
        return 1
    verb = "Would import" if args.dry_run else "Imported"
    print(f"\n{verb} into {url}:  {stats['inserted']} new, {stats['updated']} updated"
          + (f", {stats['skipped_existing']} skipped (already exist)" if stats["skipped_existing"] else "")
          + (f", {stats['skipped_missing']} skipped (not in database)" if stats["skipped_missing"] else ""))
    if args.dry_run:
        print("Dry run: nothing was changed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
